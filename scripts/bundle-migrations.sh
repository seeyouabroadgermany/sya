#!/usr/bin/env bash
# Joins every migration into one file for pasting into the Supabase SQL Editor.
# Run after adding a migration: npm run db:bundle
set -euo pipefail
out=supabase/setup/all-in-one.sql
{
  echo "-- SYB CRM: complete database setup in one file (generated by npm run db:bundle)."
  echo "-- Paste into Supabase > SQL Editor > New query and click Run, once, on a NEW project."
  for f in supabase/migrations/*.sql; do
    echo; echo "-- ===================================================================="
    echo "-- $(basename "$f")"
    echo "-- ===================================================================="
    cat "$f"
  done
} > "$out"
echo "Wrote $out"
